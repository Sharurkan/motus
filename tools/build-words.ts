// Builds the word lists of src/game/words/ from Lexique 3.83 (run: npm run words).
// The Lexique file is downloaded once into tools/.cache/, which git ignores.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { WORD_LENGTHS } from '../src/game/config.ts';
import { acceptedWords, parseBlocklist, parseLexique, secretWords } from './lexique.ts';

const LEXIQUE_URL = 'http://www.lexique.org/databases/Lexique383/Lexique383.tsv';
const CACHE_DIR = new URL('.cache/', import.meta.url);
const LEXIQUE_FILE = new URL('Lexique383.tsv', CACHE_DIR);
const BLOCKLIST_FILE = new URL('secret-blocklist.txt', import.meta.url);
const WORDS_DIR = new URL('../src/game/words/', import.meta.url);
/** Most frequent base forms kept per length: the spec asks for at least 400. */
const SECRET_WORDS_PER_LENGTH = 600;

const HEADER =
  '// Generated by tools/build-words.ts from Lexique 3.83 (www.lexique.org),\n' +
  '// licence CC BY-SA 4.0. Do not edit by hand: change the tool and run npm run words.\n';

async function readLexique(): Promise<string> {
  if (!existsSync(LEXIQUE_FILE)) {
    process.stdout.write(`Downloading ${LEXIQUE_URL}\n`);
    const response = await fetch(LEXIQUE_URL);
    if (!response.ok) throw new Error(`Download failed: HTTP ${String(response.status)}`);
    mkdirSync(CACHE_DIR, { recursive: true });
    writeFileSync(LEXIQUE_FILE, await response.text());
  }
  return readFileSync(LEXIQUE_FILE, 'utf8');
}

function writeValidWords(length: number, words: readonly string[]): void {
  const source = `${HEADER}export const VALID_WORDS = '${words.join('')}';\n`;
  writeFileSync(new URL(`valid-${String(length)}.ts`, WORDS_DIR), source);
}

function writeSecretWords(length: number, words: readonly string[]): void {
  const lines = words.map((word) => `  '${word}',\n`).join('');
  const source = `${HEADER}export const SECRET_WORDS: readonly string[] = [\n${lines}];\n`;
  writeFileSync(new URL(`secret-${String(length)}.ts`, WORDS_DIR), source);
}

async function main(): Promise<void> {
  const rows = parseLexique(await readLexique());
  const blocklist = parseBlocklist(readFileSync(BLOCKLIST_FILE, 'utf8'));
  const valid = acceptedWords(rows, WORD_LENGTHS);
  const secret = secretWords(rows, WORD_LENGTHS, blocklist, SECRET_WORDS_PER_LENGTH);
  for (const length of WORD_LENGTHS) {
    const validWords = valid.get(length) ?? [];
    const secretList = secret.get(length) ?? [];
    writeValidWords(length, validWords);
    writeSecretWords(length, secretList);
    process.stdout.write(
      `${String(length)} letters: ${String(validWords.length)} valid, ${String(secretList.length)} secret\n`,
    );
  }
}

await main();
