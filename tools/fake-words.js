// Phase 1 only (removed in phase 2): writes fake valid-word lists of the size
// expected from Lexique, to measure loading and lookups on the Fire TV Stick.
import { writeFileSync } from 'node:fs';
import { URL } from 'node:url';

/** Rough number of valid words per length, before the real lists exist. */
const COUNTS = { 6: 12000, 7: 16000, 8: 18000, 9: 16000, 10: 13000 };
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

/** Small seeded generator (mulberry32): the same files on every run. */
function seeded(seed) {
  let state = seed;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function fakeWords(length, count, random) {
  const words = new Set();
  while (words.size < count) {
    let word = '';
    for (let i = 0; i < length; i++) word += LETTERS.charAt(Math.floor(random() * 26));
    words.add(word);
  }
  return [...words].sort();
}

for (const [key, count] of Object.entries(COUNTS)) {
  const length = Number(key);
  const words = fakeWords(length, count, seeded(length));
  const source =
    '// Generated by tools/fake-words.js: do not edit by hand.\n' +
    `export const VALID_WORDS = '${words.join('')}';\n`;
  writeFileSync(new URL(`../src/game/words/valid-${key}.ts`, import.meta.url), source);
}
